"""全局配置：路径、模型名、检索参数。改这里即可，别散落在各模块里。"""
from __future__ import annotations

from pathlib import Path

# ---------- 路径 ----------
PROJECT_ROOT = Path(__file__).resolve().parent.parent
DOCS_DIR = PROJECT_ROOT / "data" / "docs"        # 原始文档（按场景分子目录）
INDEX_DIR = PROJECT_ROOT / "data" / "index"      # 向量索引持久化目录

# 场景划分：data/docs/ 下的子目录名即场景名
#   data/docs/制度文件/  → 制度问答场景
#   data/docs/运维手册/  → 操作辅助 / 报错解读场景
SCENARIOS = ["制度文件", "运维手册"]

# ---------- 模型 ----------
# LLM：通过 Ollama 本地运行，默认面壁 MiniCPM 系列（端侧小钢炮）
#   先执行：ollama pull minicpm-v
LLM_MODEL = "minicpm-v"
OLLAMA_URL = "http://localhost:11434"
# 模型常驻内存时长。Ollama 默认闲置 5 分钟就卸载模型，下次提问要重新从磁盘
# 加载 5.5GB（30-60 秒）——演示时"第一问巨慢"的元凶。设为 60 分钟，
# 演示全程模型驻留，每问稳定在推理本身的时间（10 秒级）。
LLM_KEEP_ALIVE = "60m"

# Embedding：中文语义向量模型，本地运行，首次自动下载（约 95MB）
EMBED_MODEL = "BAAI/bge-small-zh-v1.5"

# ---------- 切分参数 ----------
# 制度问答的检索单元应该"一条一切片"：用户问的就是"第几条怎么规定"，
# 把相邻三条合成一片会让引用定位模糊、语义被稀释。实测 500 字时
# 第三十九条和第四十条经常被合进同一切片，检索到"预备费"也说不清是哪一条。
# 调成 300 后基本做到一条一片（法规条款平均 150 字）。
CHUNK_SIZE = 300       # 单个切片目标字符数
CHUNK_OVERLAP = 0      # 条款本身是完整语义单元，不需要重叠（重叠反而污染上下文）

# ---------- 检索参数 ----------
# 送进提示词的条款数。3 条足够回答单条制度问题，5 条会让 M1 上的小模型
# 预填充变长、明显拖慢首字时间（实测 5 条时平均 28 秒，3 条降到 15 秒级）。
TOP_K = 3

# 置信度分级阈值（纯语义余弦相似度，0~1）。三档对应界面上三种颜色标签：
#   cos >= CONF_HIGH                     → 依据充分（绿）
#   CONF_LOW <= cos < CONF_HIGH          → 部分依据（黄）
#   cos < CONF_LOW                       → 无依据，直接拒答（红）
#
# 重要：判档用的是 embedding 余弦（cos），不是混合检索的排序分。
# 排序分 = 0.6*cos + 0.4*字面重合，字面重合会让"含领域词但答不了"的问题虚高，
# 用它判档会把「我们单位去年非税收入多少」判成依据充分。
#
# 这两个值是在本项目真实语料上跑 benchmark.py 得出的：
#   正例 cos 0.49~0.84，负例 cos 0.43~0.59 —— 重叠区靠后面两道闸兜。
# 所以阈值只做"明显无关"的粗筛，真正判答不答由条款号校验 + 模型自述决定。
CONF_HIGH = 0.62
CONF_LOW = 0.52

# 灰档下界（闸一专用）。cos 在 [CONF_GRAY, CONF_LOW) 的问题不硬拒，改为展示
# 最相关条款原文供参考。背景：实测发现"目的类"真问题（"预算法为什么编制"，
# 对应第一条"为了……制定本法"）cos 只有 0.46~0.48，而部分超纲问题反而 0.53+——
# 阈值区分度不足，降阈值会放进垃圾问题。灰档不生成答案、只展示原文，
# 所以即使误入灰档也没有编造风险，只是把"拒答"变成"拒答 + 给线索"。
CONF_GRAY = 0.42

# ---------- 生成参数 ----------
# 制度问答的答案 200 字内说得清；上限压低能显著减少小模型的空话和耗时。
MAX_TOKENS = 320
TEMPERATURE = 0.3      # 制度问答要稳，温度调低
REQUEST_TIMEOUT = 180  # Ollama 首次加载模型较慢，给足超时
